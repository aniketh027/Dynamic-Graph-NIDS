"""Generate or check C3B's manifest from the backend descriptor, without ML."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from backend.app.services.csv_schema import csv_descriptor

TARGET = ROOT / "frontend/src/lib/csv-schema.generated.ts"


def render():
    return ("// Generated by scripts/generate-csv-schema.py; do not edit manually.\n"
            "export const CSV_SCHEMA = " + json.dumps(csv_descriptor(), ensure_ascii=True,
                                                     sort_keys=True, indent=2)
            + " as const\n").encode("utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    expected = render()
    if args.check:
        if not TARGET.is_file() or TARGET.read_bytes() != expected:
            print("CSV schema manifest drift; regenerate with the approved Python environment.", file=sys.stderr)
            return 1
        print("CSV schema manifest matches backend authority.")
    else:
        TARGET.write_bytes(expected)
        print("Generated CSV schema manifest.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
